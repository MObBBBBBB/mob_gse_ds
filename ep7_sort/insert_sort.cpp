typedef int Elemtype;

// 插入排序在408历史真题中考察的很少，但是现实工程中直接插入排序很常用，所以这里也做一份模板以防万一

// 直接插入排序
// i前面的序列已经有序，i之后的序列无序；将i位置的元素插入到i之前的有序序列中
// 时间复杂度在最好情况下（序列已经有序）为O(n)；最坏和平均情况都是O(n^2)
// 空间复杂度为O(1)
// 稳定排序
void InsertSort(Elemtype a[], int len) {
    // i前面的序列已经是有序序列了，所以不需要从0开始，而是直接从1开始
    for (int i = 1; i < len; i++) {
        Elemtype temp = a[i];
        int j = i - 1;

        // 从后往前找到插入位置并同时移动元素（假如序列已经基本有序，这一步的移动和比较能节省很多时间）
        // 这里要注意：a[j] > temp 是大于号，保证值相同元素的先后顺序与未排序前相同
        while (j >= 0 && a[j] > temp) {
            a[j+1] = a[j];
            j--;
        }

        // 将temp保存的原来的a[i]放到找到的位置上
        a[j+1] = temp;
    }
}

// 折半插入排序
// 相比直接插入排序，通常可以减少比较次数，但不能减少元素移动次数，最坏和平均时空复杂度一样，也是稳定排序
// 但即便是有序的序列（最好情况），折半插入仍然需要O(nlogn)的时间复杂度（此时就不能减少比较次数），比不过直接插入的O(n)
void BInsertSort(Elemtype a[], int len) {
    for (int i = 1; i < len; i++) {
        // 先用二分查找找到a[i]应该存放的位置
        // 注意这里high从i-1开始，因为i之前的序列是有序的，有序序列才能用二分
        int low = 0, high = i - 1;
        while (low <= high) {
            int mid = (low + high) / 2;
            if (a[i] < a[mid]) high = mid - 1;
            // 这里要注意：让相等情况也移动low指针，保证值相同元素的先后顺序与未排序前相同
            else low = mid + 1;
        }
        
        // 移动元素
        Elemtype temp = a[i];
        for (int j = i - 1; j >= low; j--) a[j+1] = a[j];

        // 将temp保存的原来的a[i]放到找到的位置上
        a[low] = temp;
    }
}

// 希尔排序考的多，但是现实工程很少用

// 希尔排序
// 按增量d分组，每次只对增量分组内的元素进行排序；之后不断缩小增量，直到完整排序整个数组（此时d=1）
// 时间复杂度取决于增量序列，空间复杂度为O(1)，不稳定排序
// 在常见数据规模下，经验时间复杂度约为O(n^1.3)；最坏情况下则退化到直接插入排序的O(n^2)
void ShellSort(Elemtype a[], int len) {
    // 增量d采用每次除二的方法，增量序列：d1=len/2、d2=len/4、...、dn=1
    // 其实就是在直接插入外面套了一层壳，之后的临时变量变动的幅度由d控制
    for (int d = len / 2; d > 0; d /= 2) {
        // 这里要注意：循环后处理要让i++，这样才能处理每一个增量分组
        // 这里是处理完一个元素之后切换到另一个分组处理，所以要用 i < len，保证所有元素都被处理
        for (int i = d; i < len; i++) {
            Elemtype temp = a[i];
            int j = i - d;

            while (j >= 0 && a[j] > temp) {
                a[j+d] = a[j];
                j -= d;
            }

            a[j + d] = temp;
        }
    }
}